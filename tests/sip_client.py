#!/usr/bin/env python3
"""sip_client.py — minimal SIP client for the QEMU bench (tests/run-qemu-test.sh), no dependencies.

Plays the LAN SIP client ("linphone" endpoint of the pjsip.conf generated by rut360gw-config),
with MD5 digest authentication, against the bench Asterisk (loopback):
  register                  REGISTER
  echo <ext>                INVITE to the echo test (600), 150 G.711u RTP packets, echo received, BYE
  message <number> <text>   SIP MESSAGE (SMS bridge: sms-out context)
  call <number>             INVITE to the mobile network (chan_quectel, simulated modem): waits for
                            the final response, then ACK, a few seconds of call and BYE
                            (--vanish: disappears after the answer, without RTP or BYE)
Each command prints "<METHOD> ... -> <code>"; exit code 0 if the scenario succeeds.
"""
import argparse, hashlib, os, re, socket, struct, sys, time

ap = argparse.ArgumentParser()
ap.add_argument("cmd", choices=["register", "echo", "message", "call"])
ap.add_argument("args", nargs="*")
ap.add_argument("--server", default="127.0.0.1:5060")
ap.add_argument("--port", type=int, default=5070, help="local SIP port")
ap.add_argument("--rtp", type=int, default=40000, help="local RTP port")
ap.add_argument("--endpoint", default="linphone")
ap.add_argument("--user", default="test")
ap.add_argument("--password", default="testpass")
ap.add_argument("--wait", type=float, default=30, help="wait for the final response to an INVITE (s)")
ap.add_argument("--hold", type=float, default=3, help="duration of the answered call before BYE (s)")
ap.add_argument("--vanish", action="store_true",
                help="call: disappears after the answer, without RTP or BYE (server or softphone lost mid-call)")
a = ap.parse_args()

host, port = a.server.rsplit(":", 1)
SRV = (host, int(port))
ME = ("127.0.0.1", a.port)
s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
s.bind(ME)
s.settimeout(8)
md5 = lambda x: hashlib.md5(x.encode()).hexdigest()
cseq = [0]
FROM_TAG = os.urandom(4).hex()


def auth(challenge, method, uri):
    f = dict(re.findall(r'(\w+)="?([^",]+)"?', challenge))
    ha1 = md5(f"{a.user}:{f['realm']}:{a.password}")
    ha2 = md5(f"{method}:{uri}")
    h = f'Digest username="{a.user}",realm="{f["realm"]}",nonce="{f["nonce"]}",uri="{uri}",algorithm=MD5'
    if "qop" in f:
        nc, cn = "00000001", os.urandom(4).hex()
        resp = md5(f"{ha1}:{f['nonce']}:{nc}:{cn}:auth:{ha2}")
        h += f',qop=auth,nc={nc},cnonce="{cn}"'
    else:
        resp = md5(f"{ha1}:{f['nonce']}:{ha2}")
    h += f',response="{resp}"'
    if "opaque" in f:
        h += f',opaque="{f["opaque"]}"'
    return h


def send(method, uri, callid, extra="", body="", ctype="", to_tag="", cs=None):
    if cs is None:
        cseq[0] += 1
        cs = cseq[0]
    # REGISTER: the AOR is in To (sip:<endpoint>@...); otherwise, the user of the request URI
    to_user = a.endpoint if method == "REGISTER" else uri.split(":")[1].split("@")[0]
    m = (f"{method} {uri} SIP/2.0\r\n"
         f"Via: SIP/2.0/UDP {ME[0]}:{ME[1]};branch=z9hG4bK{os.urandom(6).hex()};rport\r\n"
         f"From: <sip:{a.endpoint}@{SRV[0]}>;tag={FROM_TAG}\r\n"
         f"To: <sip:{to_user}@{SRV[0]}>{to_tag}\r\n"
         f"Call-ID: {callid}\r\nCSeq: {cs} {method}\r\n"
         f"Contact: <sip:{a.endpoint}@{ME[0]}:{ME[1]}>\r\nMax-Forwards: 70\r\nUser-Agent: rut360gw-bench\r\n{extra}")
    if body:
        m += f"Content-Type: {ctype}\r\n"
    m += f"Content-Length: {len(body.encode())}\r\n\r\n{body}"
    s.sendto(m.encode(), SRV)


def hdr(d, name):
    m = re.search(rf"^{name}:\s*(.*)$", d, re.M | re.I)
    return m.group(1).strip() if m else ""


def recv(callid, timeout=8.0):
    """final response (>= 200) to the current transaction; requests from the server (OPTIONS...): 200"""
    end = time.time() + timeout
    while time.time() < end:
        s.settimeout(max(0.1, end - time.time()))
        try:
            d = s.recvfrom(16384)[0].decode(errors="replace")
        except socket.timeout:
            break
        if not d.startswith("SIP/2.0"):
            # request from Asterisk (qualify OPTIONS, BYE...): plain 200 OK
            lines = [l for l in d.split("\r\n") if re.match(r"^(Via|From|To|Call-ID|CSeq):", l, re.I)]
            s.sendto(("SIP/2.0 200 OK\r\n" + "\r\n".join(lines) + "\r\nContent-Length: 0\r\n\r\n").encode(), SRV)
            continue
        if hdr(d, "Call-ID") != callid:
            continue
        code = int(d.split()[1])
        if code >= 200:
            return code, d
    return 0, ""


def ack(uri, callid, to, cs):
    m = (f"ACK {uri} SIP/2.0\r\nVia: SIP/2.0/UDP {ME[0]}:{ME[1]};branch=z9hG4bK{os.urandom(6).hex()};rport\r\n"
         f"From: <sip:{a.endpoint}@{SRV[0]}>;tag={FROM_TAG}\r\nTo: {to}\r\nCall-ID: {callid}\r\n"
         f"CSeq: {cs} ACK\r\nMax-Forwards: 70\r\nContent-Length: 0\r\n\r\n")
    s.sendto(m.encode(), SRV)


def transaction(method, uri, extra="", body="", ctype="", timeout=8.0):
    """request, then a second time with authentication if the server asks for it"""
    callid = os.urandom(8).hex()
    send(method, uri, callid, extra, body, ctype)
    code, d = recv(callid, timeout)
    if code in (401, 407):
        if method == "INVITE":
            ack(uri, callid, hdr(d, "To"), cseq[0])
        h = "Authorization" if code == 401 else "Proxy-Authorization"
        ch = hdr(d, "WWW-Authenticate") or hdr(d, "Proxy-Authenticate")
        send(method, uri, callid, extra + f"{h}: {auth(ch, method, uri)}\r\n", body, ctype)
        code, d = recv(callid, timeout)
    return code, d, callid


def bye(d, callid, uri):
    target = re.search(r"<([^>]+)>", hdr(d, "Contact") or f"<{uri}>").group(1)
    cseq[0] += 1
    m = (f"BYE {target} SIP/2.0\r\nVia: SIP/2.0/UDP {ME[0]}:{ME[1]};branch=z9hG4bK{os.urandom(6).hex()};rport\r\n"
         f"From: <sip:{a.endpoint}@{SRV[0]}>;tag={FROM_TAG}\r\nTo: {hdr(d, 'To')}\r\nCall-ID: {callid}\r\n"
         f"CSeq: {cseq[0]} BYE\r\nMax-Forwards: 70\r\nContent-Length: 0\r\n\r\n")
    s.sendto(m.encode(), SRV)
    code, _ = recv(callid)
    print("BYE ->", code or "no response")
    return code == 200


def sdp():
    return (f"v=0\r\no=- 1 1 IN IP4 {ME[0]}\r\ns=-\r\nc=IN IP4 {ME[0]}\r\nt=0 0\r\n"
            f"m=audio {a.rtp} RTP/AVP 0\r\na=rtpmap:0 PCMU/8000\r\na=ptime:20\r\n")


ok = False
if a.cmd == "register":
    code, _, _ = transaction("REGISTER", f"sip:{SRV[0]}", extra="Expires: 300\r\n")
    print("REGISTER ->", code)
    ok = code == 200
elif a.cmd == "echo":
    ext = a.args[0] if a.args else "600"
    uri = f"sip:{ext}@{SRV[0]}"
    code, d, callid = transaction("INVITE", uri, body=sdp(), ctype="application/sdp", timeout=a.wait)
    print(f"INVITE {ext} ->", code or "no final response")
    if code == 200:
        ack(uri, callid, hdr(d, "To"), cseq[0])
        m = re.search(r"^c=IN IP4 (\S+)", d, re.M)
        dst = (m.group(1) if m else SRV[0], int(re.search(r"m=audio (\d+)", d).group(1)))
        r = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        r.bind((ME[0], a.rtp))
        r.settimeout(0.02)
        got = 0
        for i in range(150):
            r.sendto(struct.pack("!BBHII", 0x80, 0, i, i * 160, 0x1234) + bytes([0x55 + i % 7]) * 160, dst)
            t = time.time()
            while time.time() - t < 0.02:
                try:
                    r.recvfrom(2048)
                    got += 1
                except socket.timeout:
                    pass
        print(f"RTP: 150 sent to {dst[0]}:{dst[1]}, {got} echoed back")
        ok = got >= 50 and bye(d, callid, uri)
elif a.cmd == "message":
    num, text = a.args[0], " ".join(a.args[1:]) or "bonjour"
    code, _, _ = transaction("MESSAGE", f"sip:{num}@{SRV[0]}", body=text, ctype="text/plain")
    print(f"MESSAGE {num} ->", code)
    ok = code in (200, 202)
elif a.cmd == "call":
    num = a.args[0]
    uri = f"sip:{num}@{SRV[0]}"
    code, d, callid = transaction("INVITE", uri, body=sdp(), ctype="application/sdp", timeout=a.wait)
    print(f"INVITE {num} ->", code or "no final response")
    if code == 200:
        ack(uri, callid, hdr(d, "To"), cseq[0])
        if a.vanish:
            print("vanished: no RTP, no BYE")
            ok = True
        else:
            time.sleep(a.hold)
            ok = bye(d, callid, uri)
    elif code:
        ack(uri, callid, hdr(d, "To"), cseq[0])
sys.exit(0 if ok else 1)
